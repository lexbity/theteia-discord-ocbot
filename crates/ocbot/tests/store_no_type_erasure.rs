//! Structural guard for the typed store actor (SPEC-002 §4.1, FR-1..FR-5).
//!
//! The store's message set is a typed enum; replies travel over per-variant
//! oneshot channels. This test reads the source so a reintroduced
//! `Box<dyn Any>` / `TypeMismatch` / erased `call` path turns red.

#![allow(
    clippy::unwrap_used,
    clippy::expect_used,
    clippy::panic,
    reason = "integration tests assert by unwrapping and panicking (C6)"
)]

/// Patterns that must not exist in the store adapter. `Box<dyn` covers both the
/// message-set erasure and the CAS `ToSql` trait objects (D-8).
const BANNED: &[&str] = &[
    "Box<dyn",
    "TypeMismatch",
    "type Job",
    "type Request",
    "pub async fn call",
];

#[test]
fn store_has_no_type_erasure() {
    let source = include_str!("../src/adapters/store.rs");
    for banned in BANNED {
        assert!(
            !source.contains(banned),
            "store.rs still contains {banned:?}; the message set must stay typed"
        );
    }
    // The typed artifacts are generated by `store_method!` (Phase 6), so assert
    // the macro exists and emits the enum, dispatcher, and methods.
    assert!(
        source.contains("macro_rules! store_method"),
        "the store_method! codegen macro is missing"
    );
    assert!(
        source.contains("enum $enum"),
        "the macro must generate the typed request enum"
    );
    assert!(
        source.contains("impl $handle"),
        "the macro must generate the public handle methods"
    );
    assert!(
        source.contains("fn dispatch("),
        "the typed dispatcher is missing"
    );
    assert!(
        source.contains("StoreRequest, StoreHandle;"),
        "the production message set must be declared through the macro"
    );
}
